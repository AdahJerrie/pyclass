# Functions are where Python starts becoming much more powerful because you'll learn how to take code you've written and turn it into reusable pieces.
# A function is a reusable block of code that performs a specific job.

def greet(name):
    return f"Hello, {name}"

message = greet("Jerrie")
print(message)

# Important distinction

# Parameter = variable defined by the function.

# Argument = actual value you pass to the function.